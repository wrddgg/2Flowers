PROMPT_ANALYZE_IMAGE = """你是一名画面美学解读助手。请分析这张图片，为它生成一段富有诗意的解读。

请输出严格合法的JSON（不要输出Markdown）：

{{
  "title": "日落为礼",
  "style": "印象派 · 暖调光影",
  "palette": ["#E8A87C", "#C38D9E", "#8E6C8A", "#F2D49B", "#5B7B7A"],
  "mood": "温柔、松弛、治愈",
  "content": "黄昏时分的海面，落日余晖洒在波浪上，天空被染成蜜桃色与淡紫，远处有模糊的山影。",
  "scene": {{ "person": false, "place": "海边", "architecture": null, "time": "黄昏" }},
  "segments": [
    {{ "label": "天空", "bbox": [0, 0, 1, 0.35] }},
    {{ "label": "海面", "bbox": [0, 0.35, 1, 1] }}
  ]
}}

要求：
1. title：为画面起一个 4~6 字的诗意名字，优美含蓄，不落俗套。
2. style：画面风格，格式如"流派 · 特点"，例如"印象派 · 暖调光影"。
3. palette：从画面提取 4~6 个主色调，用 hex 色值（大写，如 #E8A87C），按视觉占比排序。
4. mood：3 个情绪词，用顿号分隔，如"温柔、松弛、治愈"。
5. content：一两句话描述画面内容，语言优美。
6. scene：场景识别。person 表示是否有人物（true/false）；place 为地点（无则 null）；architecture 为建筑（无则 null）；time 为时间（如黄昏，无则 null）。
7. segments：把画面按内容分成 1~4 个区域，bbox 用 0~1 归一化坐标 [x1, y1, x2, y2]。若画面内容单一可只返回 1 个区域。"""


